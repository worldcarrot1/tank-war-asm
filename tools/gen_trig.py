# Generates inc/trig.inc: 360-entry integer trig tables scaled x1024.
# Convention: angle in degrees, 0 = +x (right), clockwise positive on screen
# (y axis points down): 90 = down, 180 = left, 270 = up. Runtime code must be
# float-free, so tables are baked at build time and shipped as MASM data.
# Run from repo root:  python tools/gen_trig.py
import math

def tbl(f):
    return [int(round(f(math.radians(a)) * 1024)) for a in range(360)]

cosT = tbl(math.cos)
sinT = tbl(math.sin)

# self-checks: cardinal angles must be exact, tables must agree
for a in range(360):
    assert sinT[a] == cosT[(a + 270) % 360], "sin/cos identity broken at %d" % a
assert cosT[0] == 1024 and cosT[90] == 0 and cosT[180] == -1024
assert sinT[0] == 0 and sinT[90] == 1024 and sinT[270] == -1024
assert all(-1024 <= v <= 1024 for v in cosT + sinT)

def fmt(name, t):
    # MASM: each physical line must carry its own `dd` (trailing comma does
    # NOT continue across lines) -- 36 lines of 10 values per table.
    lines = []
    for i in range(0, len(t), 10):
        chunk = ", ".join("%4d" % v for v in t[i:i+10])
        if i == 0:
            lines.append("%s dd %s" % (name, chunk))
        else:
            lines.append("    dd %s" % chunk)
    return "\n".join(lines)

header = "\n".join([
    "; ============================================================",
    "; trig.inc -- GENERATED by tools/gen_trig.py, DO NOT EDIT BY HAND",
    "; 360 integer degrees, screen convention: 0=+x(right), CW positive,",
    "; 90=down, 180=left, 270=up. Scale x1024: real = tbl[a]/1024.",
    "; Consumers shift the product right by 10 (sar, NOT shr).",
    "; ============================================================",
])
text = header + "\n" + fmt("cosTBL", cosT) + "\n" + fmt("sinTBL", sinT) + "\n"

with open("inc/trig.inc", "w", newline="\r\n") as f:
    f.write(text)
print("wrote inc/trig.inc (%d bytes)" % len(text))
